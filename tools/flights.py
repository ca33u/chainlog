"""Writes Flights.lua: every flight master in QuestieDB_Forever (npcFlags bit 8)
with its faction and spot. Run after a QuestieDB update:
    python3 tools/flights.py > Flights.lua
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qdb

# Moonglade's druid-only flights: not part of the normal network.
SKIP = {11798, 11800}

m = qdb.load()
s = lambda v: v.decode() if isinstance(v, bytes) else v
rows = []
for k in m:
    mm = re.match(r"X-Npc-(\d+)-S$", k)
    if not mm:
        continue
    row = qdb.decode(m[k])
    if isinstance(row, list):
        row = {i + 1: v for i, v in enumerate(row)}
    flags = row.get(15) or 0
    nid = int(mm.group(1))
    if not (isinstance(flags, int) and flags & 8) or nid in SKIP:
        continue
    sp = m.get("X-Npc-%d-7" % nid)
    spawns = qdb.decode(sp) if sp else {}
    for area, pts in sorted((spawns or {}).items()):
        if pts and pts[0][0] > 0:
            rows.append((nid, s(row.get(13)) or "AH", area, pts[0][0], pts[0][1], s(row.get(1))))
            break
rows.sort(key=lambda r: (r[1], r[0]))
print("-- Generated by tools/flights.py from QuestieDB_Forever. Do not edit by hand.")
print("-- { npc, faction, area, x, y }  (name: " + "the NPC, for reading only)")
print("local _, ns = ...")
print("ns.FLIGHTS = {")
for nid, fac, area, x, y, name in rows:
    print('\t{ %d, "%s", %d, %.2f, %.2f }, -- %s' % (nid, fac, area, x, y, name))
print("}")
